const NewsDispatcher = ({ openModal }: { openModal: (t: string) => void }) => {
  const { param } = useParams<{ param: string }>()
  // Если в адресе число (например /news/3) — открываем полную новость
  if (param && /^\d+$/.test(param)) {
    return <NewsDetailPage />
  }
  // Иначе (например /news/russia) — список категории
  return <NewsListPage openModal={openModal} />
}

